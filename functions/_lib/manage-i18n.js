const MANAGE_I18N = { fr, en, de, es, pt, it, nl };

export function normalizeLocale(locale) {
  const base = String(locale || "en").toLowerCase().split("-")[0];
  return MANAGE_I18N[base] ? base : "en";
}

export function getManageText(locale) {
  return MANAGE_I18N[normalizeLocale(locale)];
}

export function localeFromAcceptLanguage(acceptLanguage) {
  const header = String(acceptLanguage || "");
  const preferred = header.split(",")[0]?.split(";")[0]?.trim().toLowerCase() || "";
  return normalizeLocale(preferred);
}
